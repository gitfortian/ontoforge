# Local Windows onboarding used by run-local.ps1. No production defaults or shared passwords.
function ConvertTo-LocalProperty([string]$Value) {
    $result = New-Object System.Text.StringBuilder
    foreach ($character in $Value.ToCharArray()) {
        $number = [int]$character
        if ($character -eq '\') { [void]$result.Append('\\') }
        elseif ($character -eq ' ') { [void]$result.Append('\ ') }
        elseif ($character -eq "`n") { [void]$result.Append('\n') }
        elseif ($character -eq "`r") { [void]$result.Append('\r') }
        elseif ($character -eq "`t") { [void]$result.Append('\t') }
        elseif ($number -lt 32 -or $number -gt 126) { [void]$result.Append(('\u{0:x4}' -f $number)) }
        else { [void]$result.Append($character) }
    }
    return $result.ToString()
}

function ConvertFrom-LocalProperty([string]$Value) {
    $result = New-Object System.Text.StringBuilder
    for ($i = 0; $i -lt $Value.Length; $i++) {
        $character = $Value[$i]
        if ($character -ne '\') { [void]$result.Append($character); continue }
        $i++
        if ($i -ge $Value.Length) { throw 'Incomplete local property escape.' }
        switch ($Value[$i]) {
            'u' {
                if ($i + 4 -ge $Value.Length) { throw 'Incomplete Unicode property escape.' }
                [void]$result.Append([char][Convert]::ToInt32($Value.Substring($i + 1, 4), 16)); $i += 4
            }
            'n' { [void]$result.Append("`n") }
            'r' { [void]$result.Append("`r") }
            't' { [void]$result.Append("`t") }
            default { [void]$result.Append($Value[$i]) }
        }
    }
    return $result.ToString()
}

function Read-LocalProperties([string]$Path) {
    $values = @{}
    if (-not (Test-Path -LiteralPath $Path)) { return $values }
    $content = [IO.File]::ReadAllLines($Path)
    if ($content.Count -eq 0 -or $content[0] -ne '# OntoForge local development - generated by run-local.ps1') {
        throw 'config/application.properties already exists and is not owned by the local launcher. Preserve it and configure the environment explicitly.'
    }
    foreach ($line in $content) {
        if ($line -match '^([^#=]+)=(.*)$') { $values[$matches[1]] = ConvertFrom-LocalProperty $matches[2] }
    }
    return $values
}

function Write-LocalProperties([string]$Path, [hashtable]$Values) {
    $directory = Split-Path -Parent $Path
    if (Test-Path -LiteralPath $directory) {
        if ((Get-Item -LiteralPath $directory).Attributes -band [IO.FileAttributes]::ReparsePoint) { throw 'Local config directory must not be a symbolic link.' }
    } else { [void][IO.Directory]::CreateDirectory($directory) }
    if (Test-Path -LiteralPath $Path) {
        if ((Get-Item -LiteralPath $Path).Attributes -band [IO.FileAttributes]::ReparsePoint) { throw 'Local config must not be a symbolic link.' }
    } else { [IO.File]::WriteAllText($Path, '') }
    # Remove inherited read access BEFORE writing any credential. This helper is Windows-only.
    $identity = [Security.Principal.WindowsIdentity]::GetCurrent().User
    $acl = New-Object Security.AccessControl.FileSecurity
    $acl.SetOwner($identity)
    $acl.SetAccessRuleProtection($true, $false)
    $rule = New-Object Security.AccessControl.FileSystemAccessRule($identity, 'FullControl', 'Allow')
    [void]$acl.AddAccessRule($rule)
    Set-Acl -LiteralPath $Path -AclObject $acl
    $lines = @('# OntoForge local development - generated by run-local.ps1')
    foreach ($key in ($Values.Keys | Sort-Object)) { $lines += $key + '=' + (ConvertTo-LocalProperty ([string]$Values[$key])) }
    [IO.File]::WriteAllLines($Path, $lines, (New-Object Text.UTF8Encoding($false)))
}

function Get-LocalSetting([string]$Name, [hashtable]$Saved, [string]$Key, [string]$Default = '') {
    $canonical = [Environment]::GetEnvironmentVariable(($Key.ToUpperInvariant() -replace '[.-]', '_'), 'Process')
    if (-not [string]::IsNullOrEmpty($canonical)) { return $canonical }
    $external = [Environment]::GetEnvironmentVariable($Name, 'Process')
    if (-not [string]::IsNullOrEmpty($external)) { return $external }
    if ($Saved.ContainsKey($Key)) { return [string]$Saved[$Key] }
    return $Default
}

function Read-LocalSecret([string]$Prompt, [switch]$Confirm) {
    $secure = Read-Host $Prompt -AsSecureString
    try { $value = (New-Object Net.NetworkCredential('', $secure)).Password } finally { $secure.Dispose() }
    if ($Confirm) {
        $other = Read-LocalSecret 'Confirm password'
        if ($value -cne $other) { throw 'Passwords do not match. Run the launcher again.' }
    }
    return $value
}

function Find-LocalPsql([string]$Requested) {
    if ($Requested) {
        if (-not (Test-Path -LiteralPath $Requested -PathType Leaf)) { throw 'The supplied psql executable does not exist.' }
        return (Resolve-Path -LiteralPath $Requested).Path
    }
    $command = Get-Command psql -ErrorAction SilentlyContinue
    if ($command) { return $command.Source }
    # Native Windows PostgreSQL can be installed outside Program Files.
    foreach ($service in @(Get-CimInstance Win32_Service -Filter "Name LIKE 'postgresql%'" -ErrorAction SilentlyContinue)) {
        if ($service.PathName -match '^"?(.+?pg_ctl\.exe)"?\s') {
            $candidate = Join-Path (Split-Path -Parent $matches[1]) 'psql.exe'
            if (Test-Path -LiteralPath $candidate -PathType Leaf) { return $candidate }
        }
    }
    throw 'PostgreSQL psql was not found. Install/start native PostgreSQL, or pass -PsqlPath with its full path.'
}

function Invoke-LocalPg($Connection, [string]$Database, [string]$Sql) {
    $arguments = @('-X', '-w', '-A', '-t', '-h', $Connection.Host, '-p', $Connection.Port,
        '-U', $Connection.Username, '-d', $Database, '-v', 'ON_ERROR_STOP=1', '-c', $Sql)
    $start = New-Object Diagnostics.ProcessStartInfo
    $start.FileName = $Connection.Psql
    $start.UseShellExecute = $false; $start.CreateNoWindow = $true
    $start.RedirectStandardOutput = $true; $start.RedirectStandardError = $true
    $start.Arguments = ($arguments | ForEach-Object { '"' + ([string]$_).Replace('"', '\"') + '"' }) -join ' '
    $start.EnvironmentVariables['PGPASSWORD'] = $Connection.Password
    $start.EnvironmentVariables['PGCONNECT_TIMEOUT'] = '3'
    $start.EnvironmentVariables['PGCLIENTENCODING'] = 'UTF8'
    $process = New-Object Diagnostics.Process
    $process.StartInfo = $start
    try {
        [void]$process.Start()
        $output = $process.StandardOutput.ReadToEndAsync(); $errorOutput = $process.StandardError.ReadToEndAsync()
        if (-not $process.WaitForExit(8000)) { $process.Kill(); throw 'PostgreSQL local connection timed out.' }
        if ($process.ExitCode -ne 0) { throw 'PostgreSQL connection/query failed. Check the service, role and password; use -Reconfigure to enter a new password. No saved data was removed.' }
        return $output.GetAwaiter().GetResult().Trim()
    } finally { $process.Dispose() }
}

function Initialize-LocalEnvironment([string]$Root, [string]$PsqlPath, [bool]$NonInteractive, [bool]$Reconfigure) {
    # Keep DB_* caller overrides above the generated Spring properties, including
    # when the same checkout is deliberately started in JWT compatibility mode.
    foreach ($pair in @(@('DB_URL', 'SPRING_DATASOURCE_URL'), @('DB_USERNAME', 'SPRING_DATASOURCE_USERNAME'), @('DB_PASSWORD', 'SPRING_DATASOURCE_PASSWORD'))) {
        $value = [Environment]::GetEnvironmentVariable($pair[0], 'Process')
        if ($value -and -not [Environment]::GetEnvironmentVariable($pair[1], 'Process')) {
            [Environment]::SetEnvironmentVariable($pair[1], $value, 'Process')
        }
    }
    $mode = $env:ONTOFORGE_SECURITY_AUTHENTICATION_MODE
    $profiles = @($env:SPRING_PROFILES_ACTIVE -split ',')
    # Preserve explicitly selected compatibility/developer paths without new setup.
    if (($mode -and $mode -ne 'local-session') -or $profiles -contains 'mvp-local') { return $null }
    $path = Join-Path $Root 'config/application.properties'
    if ($env:CI -eq 'true' -or ($NonInteractive -and -not (Test-Path -LiteralPath $path))) {
        if (-not $env:DB_PASSWORD -or -not $env:ONTOFORGE_OBJECTSET_CURSOR_SIGNING_SECRET -or $env:ONTOFORGE_OBJECTSET_CURSOR_SIGNING_SECRET.Length -lt 32) {
            throw 'Non-interactive startup requires DB_PASSWORD and ONTOFORGE_OBJECTSET_CURSOR_SIGNING_SECRET (32+ characters), plus explicit bootstrap credentials for an empty account database.'
        }
        return $null
    }
    $saved = Read-LocalProperties $path
    $url = Get-LocalSetting 'DB_URL' $saved 'spring.datasource.url' 'jdbc:postgresql://127.0.0.1:5432/ontoforge'
    $hostAddress = if ($env:SERVER_ADDRESS) { $env:SERVER_ADDRESS } elseif ($env:S0_HOST) { $env:S0_HOST } else { '127.0.0.1' }
    if ($hostAddress -notin @('127.0.0.1', 'localhost') -or $url -notmatch '^jdbc:postgresql://(127\.0\.0\.1|localhost)(?::([0-9]+))?/([a-z_][a-z0-9_]{0,62})$') {
        if ($saved.Count -gt 0) { throw 'Saved local setup cannot be used for a remote/non-loopback deployment. Use an explicitly configured deployment directory.' }
        return $null
    }
    $pgHost = $matches[1]; $pgPort = if ($matches[2]) { $matches[2] } else { '5432' }; $database = $matches[3]
    if ([Environment]::OSVersion.Platform -ne [PlatformID]::Win32NT) { throw 'Automatic local setup currently supports Windows. Supply explicit environment variables and -NonInteractive elsewhere.' }
    $connection = [pscustomobject]@{Host=$pgHost; Port=$pgPort; Database=$database;
        Username=(Get-LocalSetting 'DB_USERNAME' $saved 'spring.datasource.username' 'postgres');
        Password=(Get-LocalSetting 'DB_PASSWORD' $saved 'spring.datasource.password'); Psql=(Find-LocalPsql $PsqlPath)}
    if ($Reconfigure -and -not $env:DB_PASSWORD -and -not $env:SPRING_DATASOURCE_PASSWORD) { $connection.Password = '' }
    if (-not $connection.Password) {
        if ($NonInteractive) { throw 'DB_PASSWORD is missing and prompting is disabled.' }
        $connection.Password = Read-LocalSecret 'Existing local PostgreSQL password (saved for this checkout)'
    }
    $exists = Invoke-LocalPg $connection 'postgres' "SELECT 1 FROM pg_database WHERE datname='$database'"
    if ($exists -ne '1') {
        if ($database -notmatch '^ontoforge(?:_test_[a-z0-9_]+)?$') { throw 'The configured database does not exist; create custom-named databases explicitly.' }
        Write-Host "Creating missing local database $database (existing databases are preserved)."
        [void](Invoke-LocalPg $connection 'postgres' ('CREATE DATABASE "' + $database + '"'))
    }
    $accountsExist = (Invoke-LocalPg $connection $database "SELECT to_regclass('public.platform_local_account') IS NOT NULL") -eq 't'
    $needsBootstrap = -not $accountsExist
    if ($accountsExist) { $needsBootstrap = (Invoke-LocalPg $connection $database 'SELECT count(*) FROM platform_local_account') -eq '0' }
    $secret = Get-LocalSetting 'ONTOFORGE_OBJECTSET_CURSOR_SIGNING_SECRET' $saved 'ontoforge.objectset.cursor-signing-secret'
    if (-not $secret) {
        $bytes = New-Object byte[] 32; $random = [Security.Cryptography.RandomNumberGenerator]::Create()
        try { $random.GetBytes($bytes) } finally { $random.Dispose() }
        $secret = [Convert]::ToBase64String($bytes)
    }
    if ($secret.Length -lt 32) { throw 'The supplied cursor signing secret must have at least 32 characters.' }
    $values = @{'spring.datasource.url'=$url; 'spring.datasource.username'=$connection.Username;
        'spring.datasource.password'=$connection.Password; 'ontoforge.objectset.cursor-signing-secret'=$secret}
    if ($needsBootstrap) {
        if ($env:ONTOFORGE_BOOTSTRAP_ADMIN_ENABLED -eq 'false') { throw 'The local account database is empty and bootstrap was explicitly disabled.' }
        $username = Get-LocalSetting 'ONTOFORGE_BOOTSTRAP_ADMIN_USERNAME' $saved 'ontoforge.security.bootstrap.username' 'admin'
        if ($username -notmatch '^[a-z0-9._-]{3,64}$') { throw 'Initial administrator username must contain 3-64 lowercase letters, digits, dots, underscores or hyphens.' }
        $password = Get-LocalSetting 'ONTOFORGE_BOOTSTRAP_ADMIN_PASSWORD' $saved 'ontoforge.security.bootstrap.password'
        if (-not $password) {
            if ($NonInteractive) { throw 'Initial administrator password is missing and prompting is disabled.' }
            Write-Host "First local administrator: $username"
            $password = Read-LocalSecret 'Choose administrator password (12+ characters, at most 72 UTF-8 bytes)' -Confirm
        }
        $characters = [regex]::Matches($password, '(?s)[\uD800-\uDBFF][\uDC00-\uDFFF]|.').Count
        if ([string]::IsNullOrWhiteSpace($password) -or $characters -lt 12 -or [Text.Encoding]::UTF8.GetByteCount($password) -gt 72) { throw 'Administrator password must have 12+ characters and at most 72 UTF-8 bytes.' }
        $values['ontoforge.security.bootstrap.enabled'] = 'true'
        $values['ontoforge.security.bootstrap.username'] = $username
        $values['ontoforge.security.bootstrap.password'] = $password
    }
    Write-LocalProperties $path $values
    # An explicitly empty environment value overrides an otherwise valid Spring
    # property file. Treat empty local aliases as "use the saved/default value".
    foreach ($name in @('DB_URL', 'DB_USERNAME', 'DB_PASSWORD', 'ONTOFORGE_SECURITY_AUTHENTICATION_MODE',
            'ONTOFORGE_OBJECTSET_CURSOR_SIGNING_SECRET', 'ONTOFORGE_BOOTSTRAP_ADMIN_ENABLED',
            'ONTOFORGE_BOOTSTRAP_ADMIN_USERNAME', 'ONTOFORGE_BOOTSTRAP_ADMIN_PASSWORD',
            'SPRING_DATASOURCE_URL', 'SPRING_DATASOURCE_USERNAME', 'SPRING_DATASOURCE_PASSWORD')) {
        $item = Get-Item -LiteralPath ('Env:' + $name) -ErrorAction SilentlyContinue
        if ($item -and [string]::IsNullOrEmpty($item.Value)) { Remove-Item -LiteralPath ('Env:' + $name) }
    }
    Write-Host 'Local environment ready. Credentials are stored in Git-ignored config/application.properties with a current-user-only Windows ACL.'
    return [pscustomobject]@{Path=$path; Values=$values; Connection=$connection; BootstrapPending=$needsBootstrap}
}

function Complete-LocalBootstrap($Setup) {
    if (-not $Setup -or -not $Setup.BootstrapPending) { return $true }
    if ((Invoke-LocalPg $Setup.Connection $Setup.Connection.Database 'SELECT count(*) FROM platform_local_account') -eq '0') { return $false }
    foreach ($key in @('ontoforge.security.bootstrap.enabled', 'ontoforge.security.bootstrap.username', 'ontoforge.security.bootstrap.password')) { $Setup.Values.Remove($key) }
    Write-LocalProperties $Setup.Path $Setup.Values
    $Setup.BootstrapPending = $false
    Write-Host 'Administrator initialized. Bootstrap password removed from local configuration.'
    return $true
}
