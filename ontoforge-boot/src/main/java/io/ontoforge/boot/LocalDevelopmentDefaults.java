package io.ontoforge.boot;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.LinkOption;
import java.nio.file.Path;
import java.nio.file.attribute.AclEntry;
import java.nio.file.attribute.AclEntryPermission;
import java.nio.file.attribute.AclEntryType;
import java.nio.file.attribute.AclFileAttributeView;
import java.nio.file.attribute.PosixFilePermission;
import java.security.SecureRandom;
import java.util.Arrays;
import java.util.Base64;
import java.util.EnumSet;
import java.util.List;
import java.util.Properties;
import java.util.Set;
import java.util.stream.Stream;

/** Creates one private cursor key for the explicitly local IDEA run profile. */
final class LocalDevelopmentDefaults {
    private static final String PROFILE = "idea-local";
    private static final String SECRET = "ontoforge.objectset.cursor-signing-secret";
    private static final String PROPERTY = SECRET + "=";
    private static final SecureRandom RANDOM = new SecureRandom();

    private LocalDevelopmentDefaults() {}

    static void ensureForIdeaProfile(String[] args) {
        ensureForIdeaProfile(args, Path.of("config", "application.properties"));
    }

    static void ensureForIdeaProfile(String[] args, Path configurationFile) {
        if (!ideaProfileActive(args)) return;
        try {
            String secret = ensureCursorSecret(configurationFile);
            System.setProperty(SECRET, secret);
        } catch (IOException failure) {
            throw new IllegalStateException("Cannot prepare the private IDEA development signing key", failure);
        }
    }

    static boolean ideaProfileActive(String[] args) {
        if (containsProfile(System.getenv("SPRING_PROFILES_ACTIVE"))
                || containsProfile(System.getProperty("spring.profiles.active"))) return true;
        return Arrays.stream(args).anyMatch(arg -> arg.startsWith("--spring.profiles.active=")
                && containsProfile(arg.substring(arg.indexOf('=') + 1)));
    }

    static String ensureCursorSecret(Path file) throws IOException {
        Path absolute = file.toAbsolutePath().normalize();
        Path directory = absolute.getParent();
        Files.createDirectories(directory);
        if (Files.isSymbolicLink(directory) || Files.isSymbolicLink(absolute))
            throw new IOException("Local configuration path must not be a symbolic link");

        if (!Files.exists(absolute, LinkOption.NOFOLLOW_LINKS)) {
            try {
                Files.createFile(absolute);
                restrictToCurrentUser(absolute);
            } catch (java.nio.file.FileAlreadyExistsException concurrentCreate) {
                // Another IDEA launch won the create race; read its completed properties below.
            }
        }

        synchronized (LocalDevelopmentDefaults.class) {
            Properties properties = new Properties();
            try (var reader = Files.newBufferedReader(absolute, StandardCharsets.UTF_8)) {
                properties.load(reader);
            }
            String configured = properties.getProperty(SECRET, "").trim();
            if (!configured.isEmpty()) {
                if (configured.length() < 32) throw new IOException("Configured local signing key is shorter than 32 characters");
                return configured;
            }

            restrictToCurrentUser(absolute);
            byte[] bytes = new byte[32];
            RANDOM.nextBytes(bytes);
            String generated = Base64.getUrlEncoder().withoutPadding().encodeToString(bytes);
            String prefix = Files.size(absolute) == 0 ? "# OntoForge local development - generated by run-local.ps1\n" : "\n";
            Files.writeString(absolute, prefix + PROPERTY + generated + "\n", StandardCharsets.UTF_8,
                    java.nio.file.StandardOpenOption.APPEND);
            restrictToCurrentUser(absolute);
            return generated;
        }
    }

    private static boolean containsProfile(String profiles) {
        if (profiles == null) return false;
        return Stream.of(profiles.split(",")).map(String::trim).anyMatch(PROFILE::equals);
    }

    private static void restrictToCurrentUser(Path path) throws IOException {
        AclFileAttributeView acl = Files.getFileAttributeView(path, AclFileAttributeView.class, LinkOption.NOFOLLOW_LINKS);
        if (acl != null) {
            var currentUser = path.getFileSystem().getUserPrincipalLookupService()
                    .lookupPrincipalByName(System.getProperty("user.name"));
            AclEntry ownerFullAccess = AclEntry.newBuilder().setType(AclEntryType.ALLOW).setPrincipal(currentUser)
                    .setPermissions(EnumSet.allOf(AclEntryPermission.class)).build();
            acl.setAcl(List.of(ownerFullAccess));
            return;
        }
        if (Files.getFileAttributeView(path, java.nio.file.attribute.PosixFileAttributeView.class,
                LinkOption.NOFOLLOW_LINKS) != null) {
            Set<PosixFilePermission> ownerOnly = EnumSet.of(PosixFilePermission.OWNER_READ, PosixFilePermission.OWNER_WRITE);
            Files.setPosixFilePermissions(path, ownerOnly);
        }
    }
}
